import { defineConfig } from 'vitest/config';
import react from '@vitejs/plugin-react';
import { VitePWA } from 'vite-plugin-pwa';

// Vite replaces Create React App (react-scripts) as the client build tool and
// dev server. Two CRA output conventions are kept deliberately:
//   - outDir 'build'  - root package.json copies ./build to ../../dist
//   - assetsDir 'static' - src/server/main.go sets the one-year Cache-Control
//     header only on paths containing "/static"
// Port 3000 is what start-server-and-test, the Cypress specs and the README use.
export default defineConfig({
  plugins: [
    react(),
    VitePWA({
      strategies: 'injectManifest',
      srcDir: 'src',
      filename: 'service-worker.ts',
      // The app registers the worker itself (src/serviceWorkerRegistration.ts).
      injectRegister: false,
      // public/manifest.json is kept as it is.
      manifest: false,
      devOptions: { enabled: false },
    }),
  ],
  server: {
    port: 3000,
    strictPort: true,
    proxy: {
      '/api': {
        target: 'http://127.0.0.1:8080',
        changeOrigin: true,
      },
    },
  },
  build: {
    outDir: 'build',
    assetsDir: 'static',
    emptyOutDir: true,
  },
  // Unit tests (Vitest replaces the Jest that came inside react-scripts).
  // The coverage include/exclude mirror the old CRA jest.collectCoverageFrom
  // list, and the 80% thresholds are the repo's standard (issue #18).
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./src/setupTests.ts'],
    // The useTable tests wrap waitFor around vi.useFakeTimers(). Testing
    // Library only auto-advances Jest's fake timers; letting Vitest's fake
    // clock advance with real time keeps waitFor working the same way CRA's
    // Jest did.
    fakeTimers: { shouldAdvanceTime: true },
    coverage: {
      provider: 'istanbul',
      reporter: ['text', 'lcov'],
      include: ['src/**/*.{js,jsx,ts,tsx}'],
      exclude: [
        'src/*.{js,jsx,ts,tsx}',
        'src/**/*.{cy.js,cy.jsx,cy.ts,cy.tsx}',
        'src/api-autogenerated/**',
        'src/app/**',
        'src/types/**',
        'src/atoms/**',
        'src/lang/**',
        'src/typescript/**',
        'src/mocks/**',
      ],
      thresholds: {
        branches: 80,
        functions: 80,
        lines: 80,
        statements: 80,
      },
    },
  },
});
